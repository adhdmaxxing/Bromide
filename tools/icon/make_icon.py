"""Draws Bromide's launcher icon: the banner's lowercase "b" (TeX Gyre Heros),
glowing with halation on night-teal, as an Android adaptive-icon vector.

    pip install fonttools
    python3 tools/icon/make_icon.py          # writes the drawables + icon.svg (preview)

Vector drawables can't blur, so the halo is the letter stroked several times,
wide and faint to narrow and bright, behind the white fill.
"""
import os
import re

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(ROOT, "app", "src", "main", "res")

BG_TOP, BG_BOTTOM = "#0A1D2A", "#0D3329"  # the banner's blue-black into green
PAPER = "#F3ECE0"


def _halo(n=18, outer=22.0, inner=1.0):
    """(stroke width in dp, color, alpha) layers: wide, faint and deep red outside, tight and
    peach inside. Many thin steps stack into a smooth falloff instead of visible rings."""
    stops = [(0.0, (0x8C, 0x08, 0x04)), (0.45, (0xE0, 0x1A, 0x0E)), (0.8, (0xFF, 0x4A, 0x1C)),
             (1.0, (0xFF, 0xB0, 0x7A))]
    out = []
    for i in range(n):
        t = i / (n - 1)
        w = outer * (inner / outer) ** t
        for (t0, c0), (t1, c1) in zip(stops, stops[1:]):
            if t <= t1:
                k = (t - t0) / (t1 - t0)
                c = tuple(round(a + (b - a) * k) for a, b in zip(c0, c1))
                break
        out.append((round(w, 2), "#%02X%02X%02X" % c, round(0.10 + 0.08 * t, 3)))
    return out


HALO = _halo()
# The letter fits this box (dp), inside the 66 dp safe zone of the 108 dp canvas: a wide
# letter fills the width, a tall one like "b" the height.
LETTER_WIDTH, LETTER_HEIGHT = 38.0, 42.0


def glyph_path(char="b"):
    font = TTFont(os.path.join(ROOT, "tools", "banner", "texgyreheros-regular.otf"))
    glyphs = font.getGlyphSet()
    g = glyphs[font.getBestCmap()[ord(char)]]
    bp = BoundsPen(glyphs)
    g.draw(bp)
    x0, y0, x1, y1 = bp.bounds
    s = min(LETTER_WIDTH / (x1 - x0), LETTER_HEIGHT / (y1 - y0))
    ox = 54 - (x1 - x0) * s / 2 - x0 * s
    oy = 54 + (y1 - y0) * s / 2 + y0 * s  # font y points up, the canvas y points down
    pen = SVGPathPen(glyphs)
    g.draw(pen)

    def tx(m):
        nums = [float(v) for v in m.group(2).replace(",", " ").split()]
        cmd = m.group(1)
        if cmd == "H":
            return "H" + fmt(ox + nums[0] * s)
        if cmd == "V":
            return "V" + fmt(oy - nums[0] * s)
        out = []
        for i in range(0, len(nums), 2):
            out += [fmt(ox + nums[i] * s), fmt(oy - nums[i + 1] * s)]
        return cmd + " ".join(out)

    return re.sub(r"([MLCQHV])([^MLCQHVZ]*)", tx, pen.getCommands())


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def main():
    d = glyph_path()
    halo = "".join(
        f'    <path android:pathData="{d}" android:strokeColor="{c}" android:strokeAlpha="{a}"\n'
        f'        android:strokeWidth="{w}" android:strokeLineJoin="round" android:fillColor="#00000000" />\n'
        for w, c, a in HALO)
    fg = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icon/make_icon.py: the banner's \"b\", glowing with halation. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f"{halo}"
        f'    <path android:pathData="{d}" android:fillColor="{PAPER}" />\n'
        "</vector>\n")
    mono = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icon/make_icon.py: themed-icon silhouette. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f'    <path android:pathData="{d}" android:fillColor="#FFFFFFFF" />\n'
        "</vector>\n")
    bg = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icon/make_icon.py: night shadows on color negative. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="20" android:startY="0"\n'
        '                android:endX="88" android:endY="108">\n'
        f'                <item android:offset="0" android:color="{BG_TOP.replace("#", "#FF")}" />\n'
        f'                <item android:offset="1" android:color="{BG_BOTTOM.replace("#", "#FF")}" />\n'
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n"
        "</vector>\n")
    notification = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icon/make_icon.py: status bar icon. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp" android:viewportWidth="54" android:viewportHeight="54">\n'
        '    <group android:translateX="-27" android:translateY="-27">\n'
        f'        <path android:pathData="{d}" android:fillColor="#FFFFFFFF" />\n'
        "    </group>\n"
        "</vector>\n")
    drawable = os.path.join(RES, "drawable")
    for name, xml in [("ic_launcher_foreground.xml", fg), ("ic_launcher_monochrome.xml", mono),
                      ("ic_launcher_background.xml", bg), ("ic_notification.xml", notification)]:
        with open(os.path.join(drawable, name), "w") as f:
            f.write(xml)

    # SVG preview, masked to a circle like a launcher would
    halo_svg = "".join(f'<path d="{d}" fill="none" stroke="{c}" stroke-opacity="{a}" stroke-width="{w}" '
                       f'stroke-linejoin="round"/>' for w, c, a in HALO)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">'
           f'<defs><linearGradient id="g" x1="20" y1="0" x2="88" y2="108" gradientUnits="userSpaceOnUse">'
           f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>'
           f'<clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath></defs>'
           f'<g clip-path="url(#c)"><rect width="108" height="108" fill="url(#g)"/>{halo_svg}'
           f'<path d="{d}" fill="{PAPER}"/></g></svg>')
    with open(os.path.join(HERE, "icon.svg"), "w") as f:
        f.write(svg)


if __name__ == "__main__":
    main()
